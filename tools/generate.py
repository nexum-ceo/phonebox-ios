# ------------------------------------------------------------------------------------------------------- Xcode project

def uid(name):
    return hashlib.md5(name.encode()).hexdigest()[:24].upper()


EXT = "PhoneBoxControls"  # the Control Center control (the Android app's Quick Settings tile)


def generate_extension_plist():
    text = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key><string>en</string>
    <key>CFBundleDisplayName</key><string>PhoneBox</string>
    <key>CFBundleExecutable</key><string>$(EXECUTABLE_NAME)</string>
    <key>CFBundleIdentifier</key><string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
    <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
    <key>CFBundleName</key><string>$(PRODUCT_NAME)</string>
    <key>CFBundlePackageType</key><string>XPC!</string>
    <key>CFBundleShortVersionString</key><string>$(MARKETING_VERSION)</string>
    <key>CFBundleVersion</key><string>$(CURRENT_PROJECT_VERSION)</string>
    <key>NSExtension</key>
    <dict>
        <key>NSExtensionPointIdentifier</key><string>com.apple.widgetkit-extension</string>
    </dict>
</dict>
</plist>
"""
    with open(os.path.join(ROOT, EXT, "Info.plist"), "w", encoding="utf-8") as f:
        f.write(text)


def generate_project(langs):
    generate_extension_plist()
    sources = sorted(f for f in os.listdir(APP) if f.endswith(".swift"))
    ext_sources = sorted(f for f in os.listdir(os.path.join(ROOT, EXT)) if f.endswith(".swift"))
    refs, builds = [], []

    def file_ref(key, path, kind):
        refs.append(f'\t\t{uid("ref:" + key)} /* {path} */ = {{isa = PBXFileReference; lastKnownFileType = {kind}; path = "{path}"; sourceTree = "<group>"; }};')
        return uid("ref:" + key)

    def build(key, ref, name, phase, settings=""):
        bid = uid("build:" + key)
        builds.append(f'\t\t{bid} /* {name} in {phase} */ = {{isa = PBXBuildFile; fileRef = {ref} /* {name} */; {settings}}};')
        return (bid, name)

    # app
    app_children, app_sources, app_resources = [], [], []
    for f in sources:
        r = file_ref("app:" + f, f, "sourcecode.swift")
        app_children.append((r, f))
        app_sources.append(build("app:" + f, r, f, "Sources"))
    r = file_ref("app:Info.plist", "Info.plist", "text.plist.xml")
    app_children.append((r, "Info.plist"))
    r = file_ref("app:Assets.xcassets", "Assets.xcassets", "folder.assetcatalog")
    app_children.append((r, "Assets.xcassets"))
    app_resources.append(build("app:Assets.xcassets", r, "Assets.xcassets", "Resources"))
    res_children = []
    for name in ["www"] + [l + ".lproj" for l in langs]:
        r = file_ref("res:" + name, name, "folder")
        res_children.append((r, name))
        app_resources.append(build("res:" + name, r, name, "Resources"))

    # extension
    ext_children, ext_sources_ids = [], []
    for f in ext_sources:
        r = file_ref("ext:" + f, f, "sourcecode.swift")
        ext_children.append((r, f))
        ext_sources_ids.append(build("ext:" + f, r, f, "Sources"))
    r = file_ref("ext:Info.plist", "Info.plist", "text.plist.xml")
    ext_children.append((r, "Info.plist"))

    product_ref, ext_product_ref = uid("product"), uid("product:ext")
    refs.append(f'\t\t{product_ref} /* PhoneBox.app */ = {{isa = PBXFileReference; explicitFileType = wrapper.application; includeInIndex = 0; path = PhoneBox.app; sourceTree = BUILT_PRODUCTS_DIR; }};')
    refs.append(f'\t\t{ext_product_ref} /* {EXT}.appex */ = {{isa = PBXFileReference; explicitFileType = "wrapper.app-extension"; includeInIndex = 0; path = {EXT}.appex; sourceTree = BUILT_PRODUCTS_DIR; }};')
    embed = build("embed:ext", ext_product_ref, f"{EXT}.appex", "Embed Foundation Extensions",
                  "settings = {ATTRIBUTES = (RemoveHeadersOnCopy, ); }; ")

    project, target, ext_target = uid("project"), uid("target"), uid("target:ext")
    res_group, app_group, ext_group, main_group, products_group = uid("g:res"), uid("g:app"), uid("g:ext"), uid("g:main"), uid("g:products")
    src_phase, res_phase, fw_phase, embed_phase = uid("phase:src"), uid("phase:res"), uid("phase:fw"), uid("phase:embed")
    ext_src, ext_res, ext_fw = uid("phase:ext:src"), uid("phase:ext:res"), uid("phase:ext:fw")
    proxy, dependency = uid("proxy:ext"), uid("dep:ext")
    proj_cfgs, tgt_cfgs, ext_cfgs = uid("cfglist:project"), uid("cfglist:target"), uid("cfglist:ext")
    proj_debug, proj_release, tgt_debug, tgt_release = uid("cfg:pd"), uid("cfg:pr"), uid("cfg:td"), uid("cfg:tr")
    ext_debug, ext_release = uid("cfg:ed"), uid("cfg:er")

    def group(gid, name, path, children):
        kids = "".join(f"\n\t\t\t\t{c} /* {n} */," for c, n in children)
        p = f'path = "{path}"; ' if path else ""
        return f'\t\t{gid} /* {name} */ = {{\n\t\t\tisa = PBXGroup;\n\t\t\tchildren = ({kids}\n\t\t\t);\n\t\t\t{p}sourceTree = "<group>";\n\t\t}};'

    def items(lst):
        return "".join(f"\n\t\t\t\t{b} /* {n} */," for b, n in lst)

    def phase(pid, isa, name, files, extra=""):
        return (f"\t\t{pid} /* {name} */ = {{\n\t\t\tisa = {isa};\n\t\t\tbuildActionMask = 2147483647;\n{extra}"
                f"\t\t\tfiles = ({items(files)}\n\t\t\t);\n\t\t\trunOnlyForDeploymentPostprocessing = 0;\n\t\t}};")

    def native(tid, name, cfgs, phases, deps, product, ptype):
        ph = "".join(f"\n\t\t\t\t{p} /* {n} */," for p, n in phases)
        dp = "".join(f"\n\t\t\t\t{d} /* PBXTargetDependency */," for d in deps)
        return (f"\t\t{tid} /* {name} */ = {{\n\t\t\tisa = PBXNativeTarget;\n\t\t\tbuildConfigurationList = {cfgs};\n\t\t\tbuildPhases = ({ph}\n\t\t\t);\n"
                f"\t\t\tbuildRules = (\n\t\t\t);\n\t\t\tdependencies = ({dp}\n\t\t\t);\n\t\t\tname = {name};\n\t\t\tproductName = {name};\n"
                f"\t\t\tproductReference = {product};\n\t\t\tproductType = \"{ptype}\";\n\t\t}};")

    def cfg(cid, name, settings):
        body = "".join(f"\n\t\t\t\t{x};" for x in settings)
        return f'\t\t{cid} /* {name} */ = {{\n\t\t\tisa = XCBuildConfiguration;\n\t\t\tbuildSettings = {{{body}\n\t\t\t}};\n\t\t\tname = {name};\n\t\t}};'

    def cfglist(lid, comment, debug, release):
        return (f"\t\t{lid} /* {comment} */ = {{\n\t\t\tisa = XCConfigurationList;\n\t\t\tbuildConfigurations = (\n\t\t\t\t{debug} /* Debug */,\n"
                f"\t\t\t\t{release} /* Release */,\n\t\t\t);\n\t\t\tdefaultConfigurationIsVisible = 0;\n\t\t\tdefaultConfigurationName = Release;\n\t\t}};")

    common = [
        "ALWAYS_SEARCH_USER_PATHS = NO", "CLANG_ENABLE_MODULES = YES", "CLANG_ENABLE_OBJC_ARC = YES",
        "ENABLE_USER_SCRIPT_SANDBOXING = NO", "IPHONEOS_DEPLOYMENT_TARGET = 16.0", "SDKROOT = iphoneos",
        "SWIFT_VERSION = 5.0", "TARGETED_DEVICE_FAMILY = 1", "CURRENT_PROJECT_VERSION = 1", f"MARKETING_VERSION = {VERSION}",
    ]
    debug_extra = ["DEBUG_INFORMATION_FORMAT = dwarf", "ENABLE_TESTABILITY = YES", "GCC_OPTIMIZATION_LEVEL = 0", "ONLY_ACTIVE_ARCH = YES",
                   'SWIFT_ACTIVE_COMPILATION_CONDITIONS = "DEBUG $(inherited)"', 'SWIFT_OPTIMIZATION_LEVEL = "-Onone"']
    release_extra = ['DEBUG_INFORMATION_FORMAT = "dwarf-with-dsym"', "ENABLE_NS_ASSERTIONS = NO", "SWIFT_COMPILATION_MODE = wholemodule",
                     'SWIFT_OPTIMIZATION_LEVEL = "-O"', "VALIDATE_PRODUCT = YES"]
    app_settings = [
        "ASSETCATALOG_COMPILER_APPICON_NAME = AppIcon", "CODE_SIGN_STYLE = Automatic", "GENERATE_INFOPLIST_FILE = NO",
        "INFOPLIST_FILE = PhoneBox/Info.plist", f"PRODUCT_BUNDLE_IDENTIFIER = {BUNDLE_ID}", "PRODUCT_NAME = PhoneBox",
        'LD_RUNPATH_SEARCH_PATHS = "$(inherited) @executable_path/Frameworks"', "ENABLE_PREVIEWS = NO",
    ]
    ext_settings = [
        "CODE_SIGN_STYLE = Automatic", "GENERATE_INFOPLIST_FILE = NO", f"INFOPLIST_FILE = {EXT}/Info.plist",
        f"PRODUCT_BUNDLE_IDENTIFIER = {BUNDLE_ID}.controls", f"PRODUCT_NAME = {EXT}", "IPHONEOS_DEPLOYMENT_TARGET = 18.0",
        "SKIP_INSTALL = YES", "APPLICATION_EXTENSION_API_ONLY = YES",
        'LD_RUNPATH_SEARCH_PATHS = "$(inherited) @executable_path/Frameworks @executable_path/../../Frameworks"',
    ]

    out = ["// !$*UTF8*$!\n{\n\tarchiveVersion = 1;\n\tclasses = {\n\t};\n\tobjectVersion = 56;\n\tobjects = {\n"]
    out += ["/* Begin PBXBuildFile section */"] + builds + ["/* End PBXBuildFile section */\n"]
    out += ["/* Begin PBXContainerItemProxy section */",
            f"\t\t{proxy} /* PBXContainerItemProxy */ = {{\n\t\t\tisa = PBXContainerItemProxy;\n\t\t\tcontainerPortal = {project} /* Project object */;\n"
            f"\t\t\tproxyType = 1;\n\t\t\tremoteGlobalIDString = {ext_target};\n\t\t\tremoteInfo = {EXT};\n\t\t}};",
            "/* End PBXContainerItemProxy section */\n"]
    out += ["/* Begin PBXCopyFilesBuildPhase section */",
            phase(embed_phase, "PBXCopyFilesBuildPhase", "Embed Foundation Extensions", [embed],
                  '\t\t\tdstPath = "";\n\t\t\tdstSubfolderSpec = 13;\n\t\t\tname = "Embed Foundation Extensions";\n'),
            "/* End PBXCopyFilesBuildPhase section */\n"]
    out += ["/* Begin PBXFileReference section */"] + refs + ["/* End PBXFileReference section */\n"]
    out += ["/* Begin PBXFrameworksBuildPhase section */", phase(fw_phase, "PBXFrameworksBuildPhase", "Frameworks", []),
            phase(ext_fw, "PBXFrameworksBuildPhase", "Frameworks", []), "/* End PBXFrameworksBuildPhase section */\n"]
    out += ["/* Begin PBXGroup section */",
            group(main_group, "PhoneBox-iOS", None, [(app_group, "PhoneBox"), (ext_group, EXT), (products_group, "Products")]),
            group(app_group, "PhoneBox", "PhoneBox", app_children + [(res_group, "Resources")]),
            group(res_group, "Resources", "Resources", res_children),
            group(ext_group, EXT, EXT, ext_children),
            group(products_group, "Products", None, [(product_ref, "PhoneBox.app"), (ext_product_ref, f"{EXT}.appex")]),
            "/* End PBXGroup section */\n"]
    out += ["/* Begin PBXNativeTarget section */",
            native(target, "PhoneBox", tgt_cfgs, [(src_phase, "Sources"), (fw_phase, "Frameworks"), (res_phase, "Resources"),
                                                   (embed_phase, "Embed Foundation Extensions")], [dependency], product_ref,
                   "com.apple.product-type.application"),
            native(ext_target, EXT, ext_cfgs, [(ext_src, "Sources"), (ext_fw, "Frameworks"), (ext_res, "Resources")], [], ext_product_ref,
                   "com.apple.product-type.app-extension"),
            "/* End PBXNativeTarget section */\n"]
    out += ["/* Begin PBXProject section */",
            f"\t\t{project} /* Project object */ = {{\n\t\t\tisa = PBXProject;\n\t\t\tattributes = {{\n\t\t\t\tBuildIndependentTargetsInParallel = 1;\n"
            f"\t\t\t\tLastSwiftUpdateCheck = 1500;\n\t\t\t\tLastUpgradeCheck = 1500;\n\t\t\t}};\n\t\t\tbuildConfigurationList = {proj_cfgs};\n"
            f"\t\t\tcompatibilityVersion = \"Xcode 14.0\";\n\t\t\tdevelopmentRegion = en;\n\t\t\thasScannedForEncodings = 0;\n"
            f"\t\t\tknownRegions = (\n\t\t\t\ten,\n\t\t\t\tBase,\n\t\t\t);\n\t\t\tmainGroup = {main_group};\n"
            f"\t\t\tproductRefGroup = {products_group} /* Products */;\n\t\t\tprojectDirPath = \"\";\n\t\t\tprojectRoot = \"\";\n"
            f"\t\t\ttargets = (\n\t\t\t\t{target} /* PhoneBox */,\n\t\t\t\t{ext_target} /* {EXT} */,\n\t\t\t);\n\t\t}};",
            "/* End PBXProject section */\n"]
    out += ["/* Begin PBXResourcesBuildPhase section */", phase(res_phase, "PBXResourcesBuildPhase", "Resources", app_resources),
            phase(ext_res, "PBXResourcesBuildPhase", "Resources", []), "/* End PBXResourcesBuildPhase section */\n"]
    out += ["/* Begin PBXSourcesBuildPhase section */", phase(src_phase, "PBXSourcesBuildPhase", "Sources", app_sources),
            phase(ext_src, "PBXSourcesBuildPhase", "Sources", ext_sources_ids), "/* End PBXSourcesBuildPhase section */\n"]
    out += ["/* Begin PBXTargetDependency section */",
            f"\t\t{dependency} /* PBXTargetDependency */ = {{\n\t\t\tisa = PBXTargetDependency;\n\t\t\ttarget = {ext_target} /* {EXT} */;\n"
            f"\t\t\ttargetProxy = {proxy} /* PBXContainerItemProxy */;\n\t\t}};",
            "/* End PBXTargetDependency section */\n"]
    out += ["/* Begin XCBuildConfiguration section */",
            cfg(proj_debug, "Debug", common + debug_extra), cfg(proj_release, "Release", common + release_extra),
            cfg(tgt_debug, "Debug", app_settings), cfg(tgt_release, "Release", app_settings),
            cfg(ext_debug, "Debug", ext_settings), cfg(ext_release, "Release", ext_settings),
            "/* End XCBuildConfiguration section */\n"]
    out += ["/* Begin XCConfigurationList section */",
            cfglist(proj_cfgs, 'Build configuration list for PBXProject "PhoneBox"', proj_debug, proj_release),
            cfglist(tgt_cfgs, 'Build configuration list for PBXNativeTarget "PhoneBox"', tgt_debug, tgt_release),
            cfglist(ext_cfgs, f'Build configuration list for PBXNativeTarget "{EXT}"', ext_debug, ext_release),
            "/* End XCConfigurationList section */"]
    out.append(f"\t}};\n\trootObject = {project} /* Project object */;\n}}\n")

    proj_dir = os.path.join(ROOT, "PhoneBox.xcodeproj")
    os.makedirs(proj_dir, exist_ok=True)
    with open(os.path.join(proj_dir, "project.pbxproj"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    languages = generate_strings()
    generate_icon(sys.argv[1] if len(sys.argv) > 1 else None)
    generate_plist(languages)
    generate_project(languages)
    print("generated:", ", ".join(languages))
