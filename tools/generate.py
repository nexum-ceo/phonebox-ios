#!/usr/bin/env python3
"""Generates the generated parts of the PhoneBox iOS project (no third-party tools needed):

  * PhoneBox/Resources/<lang>.lproj/Localizable.strings  from the Android app's strings.xml files (upstream-android-res/)
  * PhoneBox/Assets.xcassets                             the app icon, from the agent's phonebox.ico
  * PhoneBox.xcodeproj/project.pbxproj                   the Xcode project

Run from the project folder:  python3 tools/generate.py [path/to/phonebox.ico]
"""
import hashlib
import os
import re
import struct
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, "PhoneBox")
RES = os.path.join(APP, "Resources")

BUNDLE_ID = "net.oxog.phonebox.deskpanel.ios"
VERSION = "0.9.27"  # the Android app this port follows (the agent compares it with its own release)

# ---------------------------------------------------------------------------------------------------------- strings

LANG_DIRS = {  # Android values folder -> iOS .lproj
    "values": "en", "values-in": "id", "values-zh": "zh-Hans", "values-zh-rTW": "zh-Hant", "values-b+pt+BR": "pt-BR", "values-pt": "pt-PT",
}
KEYS = ["pair_title", "pair_message", "pair_positive", "pair_negative", "pair_progress", "pair_done", "pair_failed_title",
        "pair_failed_unreachable", "pair_failed_code", "pair_failed_answer", "pair_failed_certificate", "ok"]

EXTRA = {}  # the iOS app shows no strings of its own: only the Android app's


def android_to_ios(text):
    text = text.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n").replace("\\@", "@").replace("\\?", "?")
    text = re.sub(r"%(\d+)\$s", r"%\1$@", text)
    text = re.sub(r"%(\d+)\$d", r"%\1$ld", text)
    return text


def quote(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def generate_strings():
    upstream = os.path.join(ROOT, "upstream-android-res")
    langs = []
    for folder, lang in LANG_DIRS.items():
        path = os.path.join(upstream, folder, "strings.xml")
        if not os.path.exists(path):
            continue
        strings = {}
        for node in ET.parse(path).getroot().findall("string"):
            if node.get("name") in KEYS:
                strings[node.get("name")] = android_to_ios(node.text or "")
        strings.update(EXTRA.get(lang, {}))
        out = os.path.join(RES, lang + ".lproj")
        os.makedirs(out, exist_ok=True)
        with open(os.path.join(out, "Localizable.strings"), "w", encoding="utf-8") as f:
            f.write("/* Generated by tools/generate.py from the Android app's strings.xml */\n")
            for key, value in strings.items():
                f.write('"%s" = "%s";\n' % (key, quote(value)))
        langs.append(lang)
    for folder in sorted(os.listdir(upstream)):
        m = re.fullmatch(r"values-([a-z]{2,3})", folder)
        if not m or m.group(1) in ("v24", "v28") or folder in LANG_DIRS:
            continue
        lang = m.group(1)
        path = os.path.join(upstream, folder, "strings.xml")
        if not os.path.exists(path):
            continue
        strings = {}
        for node in ET.parse(path).getroot().findall("string"):
            if node.get("name") in KEYS:
                strings[node.get("name")] = android_to_ios(node.text or "")
        strings.update(EXTRA.get(lang, {}))
        out = os.path.join(RES, lang + ".lproj")
        os.makedirs(out, exist_ok=True)
        with open(os.path.join(out, "Localizable.strings"), "w", encoding="utf-8") as f:
            f.write("/* Generated by tools/generate.py from the Android app's strings.xml */\n")
            for key, value in strings.items():
                f.write('"%s" = "%s";\n' % (key, quote(value)))
        langs.append(lang)
    return sorted(langs)


# ------------------------------------------------------------------------------------------------------------- icon

def generate_icon(ico_path):
    catalog = os.path.join(APP, "Assets.xcassets")
    icon_dir = os.path.join(catalog, "AppIcon.appiconset")
    os.makedirs(icon_dir, exist_ok=True)
    with open(os.path.join(catalog, "Contents.json"), "w") as f:
        f.write('{\n  "info" : { "author" : "xcode", "version" : 1 }\n}\n')
    contents = ('{\n  "images" : [ { "filename" : "icon.png", "idiom" : "universal", "platform" : "ios", "size" : "1024x1024" } ],\n'
                '  "info" : { "author" : "xcode", "version" : 1 }\n}\n')
    with open(os.path.join(icon_dir, "Contents.json"), "w") as f:
        f.write(contents)
    target = os.path.join(icon_dir, "icon.png")
    if not ico_path or not os.path.exists(ico_path):
        print("no phonebox.ico given: keeping the existing icon (if any)")
        return
    data = open(ico_path, "rb").read()
    _, _, count = struct.unpack("<HHH", data[:6])
    best = None
    for i in range(count):
        w, h, _, _, _, _, size, offset = struct.unpack("<BBBBHHII", data[6 + 16 * i: 22 + 16 * i])
        w = w or 256
        chunk = data[offset: offset + size]
        if chunk[:8] == b"\x89PNG\r\n\x1a\n" and (best is None or w > best[0]):
            best = (w, chunk)
    if not best:
        print("phonebox.ico has no PNG image")
        return
    tmp = os.path.join(ROOT, "tools", ".icon-tmp")
    os.makedirs(tmp, exist_ok=True)
    src = os.path.join(tmp, "src.png")
    open(src, "wb").write(best[1])
    # App icons have no transparency: go through JPEG to flatten, then scale to 1024
    subprocess.run(["sips", "-s", "format", "jpeg", src, "--out", os.path.join(tmp, "flat.jpg")], check=True, capture_output=True)
    subprocess.run(["sips", "-s", "format", "png", "-z", "1024", "1024", os.path.join(tmp, "flat.jpg"), "--out", target], check=True, capture_output=True)
    for name in os.listdir(tmp):
        os.remove(os.path.join(tmp, name))
    os.rmdir(tmp)
    print("icon from the %dpx image of phonebox.ico" % best[0])


